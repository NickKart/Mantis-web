// ---------------------------------------------------------------- навигация по приложению

type Go = (tab: string) => void;
let go: Go = () => undefined;
let current: HelpTopic = "start";
let render: () => void = () => undefined;

/** Main регистрирует переход между разделами. */
export function setNavigator(fn: Go): void {
  go = fn;
}

export function openHelp(topic: HelpTopic): void {
  current = topic;
  render();
  go("help");
}

/** Кнопка «?» — открывает нужный раздел справки. */
export function helpButton(topic: HelpTopic): HTMLButtonElement {
  const b = document.createElement("button");
  b.type = "button";
  b.className = "help-btn";
  b.textContent = "?";
  const t = TOPICS.find((x) => x.id === topic);
  b.title = `Справка: ${t?.title ?? ""}`;
  b.addEventListener("click", () => openHelp(topic));
  return b;
}

export function mountHelp(root: HTMLElement): void {
  const list = document.createElement("nav");
  list.className = "help-list";
  const body = document.createElement("article");
  body.className = "help-body";
  root.append(list, body);
  render = () => {
    list.replaceChildren(...TOPICS.map((t) => {
      const b = document.createElement("button");
      b.type = "button";
      b.className = "help-topic";
      if (t.id === current) b.setAttribute("aria-current", "true");
      const i = document.createElement("span");
      i.className = "help-ico";
      i.textContent = t.icon;
      b.append(i, document.createTextNode(t.title));
      b.addEventListener("click", () => {
        current = t.id;
        render();
      });
      return b;
    }));
    const t = TOPICS.find((x) => x.id === current)!;
    const h = document.createElement("h1");
    h.textContent = t.title;
    body.replaceChildren(h, ...t.blocks.map(([title, items]) => {
      const sec = document.createElement("section");
      const p = document.createElement("p");
      p.className = "eyebrow";
      p.textContent = title;
      const ul = document.createElement("ul");
      for (const it of items) {
        const li = document.createElement("li");
        li.textContent = it;
        ul.append(li);
      }
      sec.append(p, ul);
      return sec;
    }));
    body.scrollTop = 0;
  };
  render();
}
